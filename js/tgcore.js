/* ---------- text normalisation ---------- */
const LET = /[a-zа-яіїєґё\u0301]/i;
function norm(t){
  return (t||'').toLowerCase()
    .replace(/[ёэ]/g,'е').replace(/ъ/g,'').replace(/\u0301/g,'')
    .replace(/[«»"'`]/g,' ').replace(/\s+/g,' ');
}

/* ---------- target classification ----------
   order matters: narrow classes first, broad «bpla» fallback last */
const C = '[а-яіїєґ]';
const CLS = [
  ['ballistic', new RegExp('баліст|балист|іскандер-м|искандер-м|кинджал|кинжал|кн-23|кн23|швидкісн'+C+'* ціл|быстр'+C+'* цел|скоростн'+C+'* цел')],
  ['cruise',    /крилат|крылат|калібр|калибр|х-101|х101|х-555|х-59|х-69|іскандер-к|искандер-к|нептун/],
  ['kab',       /каб-|каб |кабів|авіабомб|авиабомб|умпк|фаб-/],
  ['recon',     /розвід|развед|zala|орлан|supercam|суперкам/],
  ['aircraft',  new RegExp('міг-31|миг-31|ту-95|ту-22|ту-160|зліт|взлет|борт'+C+'* ворог')],
  ['shahed',    /шахед|shahed|геран|гербер|мопед|камікадз|камикадз|бпла|дрон/]
];
function classify(t){ for(const [k,re] of CLS){ if(re.test(t)) return k; } return 'unknown'; }

/* ---------- count ---------- */
function countOf(t){
  let m = t.match(/(\d{1,3})\s*(?:[хx]\s|[хx]\b|\s*шт|\s*(?:шахед|бпла|ціл|цел|ракет|дрон))/);
  if(m) return parseInt(m[1],10);
  m = t.match(/(?:група|груп|до)\s+(\d{1,3})/); if(m) return parseInt(m[1],10);
  return null;
}

/* ---------- relation from context before the toponym ---------- */
const REL = [
  ['toward',  new RegExp('(курс'+C+'*\\s+на|у\\s+напрямку|в\\s+напрямку|напрямок(?:\\s+на)?|рухаєтьс'+C+'*\\s+на|прямує\\s+на|летит'+C+'*\\s+на|в\\s+сторону|курсом)\\s*$')],
  ['through', /(через|повз|мимо|над|поблизу|біля|коло)\s*$/],
  ['from',    new RegExp('(з\\s+боку|зі\\s+сторони|з\\s+акваторі'+C+'*|зі\\s+сходу|з\\s+заходу|з\\s+півдня|з\\s+півночі|запуск'+C+'*\\s+з|пуск'+C+'*\\s+з|зліт'+C+'*\\s+з|вилетіл'+C+'*\\s+з)\\s*$')],
  ['at',      new RegExp('(в\\s+районі|у\\s+районі|район'+C+'*|в\\s+межах|на\\s+території)\\s*$')]
];
function relationAt(t, i){
  const before = t.slice(Math.max(0,i-34), i);
  for(const [rel,re] of REL){ if(re.test(before)) return rel; }
  return 'at';
}

/* ---------- heading words ---------- */
const HDG = [['захід',270],['західн',270],['схід',90],['східн',90],['північ',0],['північн',0],['південь',180],['південн',180],
             ['північно-захід',315],['північно-східн',45],['південно-захід',225],['південно-східн',135]];
function headingWord(t){
  let best=null, bl=0;
  HDG.forEach(([w,deg])=>{ if(t.indexOf('курс')>=0 && t.indexOf(w)>=0 && w.length>bl){ best=deg; bl=w.length; } });
  return best;
}

/* ---------- PARSER (pure) ---------- */
function parseMessage(text, ts, meta){
  if(!text) return null;
  const t = norm(text);
  const cls = classify(t);
  const seen = {}, wps = [], spans = [];
  const overlaps = (a,b)=>spans.some(sp=>a < sp[1] && b > sp[0]);
  for(const {s,e} of IDX){
    if(seen[e.n]) continue;
    let from = 0, i;
    while((i = t.indexOf(s, from)) >= 0){
      from = i + 1;
      const prev = i>0 ? t[i-1] : ' ';
      if(LET.test(prev)) continue;                 // must start a word
      // a longer toponym already claimed these characters (Дніпропетровщина vs Дніпро)
      if(overlaps(i, i+s.length)) continue;
      seen[e.n] = true;
      spans.push([i, i+s.length]);
      wps.push({ name:e.n, lat:e.ll[1], lon:e.ll[0], oblast:e.ob,
                 kind:e.k, relation:relationAt(t,i), at:i });
      break;
    }
  }
  wps.sort((a,b)=>a.at-b.at);
  if(cls==='unknown' && !wps.length) return null;
  return { msgId:(meta&&meta.msgId)||null, channel:(meta&&meta.channel)||'', ts:ts||Date.now(),
           targetClass:cls, count:countOf(t), heading:headingWord(t),
           waypoints:wps.map(w=>({name:w.name,lat:w.lat,lon:w.lon,oblast:w.oblast,kind:w.kind,relation:w.relation})),
           rawText:text };
}

/* ---------- geometry ---------- */
const R = 6371;
function hav(a,b){
  const dLat=(b[1]-a[1])*Math.PI/180, dLon=(b[0]-a[0])*Math.PI/180;
  const la1=a[1]*Math.PI/180, la2=b[1]*Math.PI/180;
  const x=Math.sin(dLat/2)**2 + Math.cos(la1)*Math.cos(la2)*Math.sin(dLon/2)**2;
  return 2*R*Math.asin(Math.min(1,Math.sqrt(x)));
}
function bearing(a,b){
  const la1=a[1]*Math.PI/180, la2=b[1]*Math.PI/180, dLon=(b[0]-a[0])*Math.PI/180;
  const y=Math.sin(dLon)*Math.cos(la2), x=Math.cos(la1)*Math.sin(la2)-Math.sin(la1)*Math.cos(la2)*Math.cos(dLon);
  return (Math.atan2(y,x)*180/Math.PI+360)%360;
}
function angDiff(a,b){ let d=Math.abs(a-b)%360; return d>180?360-d:d; }
/* Catmull-Rom through all points, sampled — smooth flight curve */
function spline(pts, per){
  if(!pts || pts.length<2) return (pts||[]).slice();
  if(pts.length===2) return [pts[0],pts[1]];
  const N = per||14, out=[];
  for(let i=0;i<pts.length-1;i++){
    const p0=pts[i-1]||pts[i], p1=pts[i], p2=pts[i+1], p3=pts[i+2]||pts[i+1];
    const last = i===pts.length-2;
    for(let k=0;k<(last?N+1:N);k++){
      const u=k/N, u2=u*u, u3=u2*u;
      out.push([
        0.5*((2*p1[0])+(-p0[0]+p2[0])*u+(2*p0[0]-5*p1[0]+4*p2[0]-p3[0])*u2+(-p0[0]+3*p1[0]-3*p2[0]+p3[0])*u3),
        0.5*((2*p1[1])+(-p0[1]+p2[1])*u+(2*p0[1]-5*p1[1]+4*p2[1]-p3[1])*u2+(-p0[1]+3*p1[1]-3*p2[1]+p3[1])*u3)
      ]);
    }
  }
  return out;
}

/* ---------- TRACKER ---------- */
const CFG = { maxKm:120, maxDtMin:40, maxTurn:100, staleMin:7, expireMin:15 };

function Tracker(cfg){
  this.cfg = Object.assign({}, CFG, cfg||{});
  this.tracks = new Map();
  this._n = 0;
}
Tracker.prototype.ingest = function(ev){
  const zones = ev.waypoints.filter(w=>w.kind==='oblast');
  const pts   = ev.waypoints.filter(w=>w.kind!=='oblast' && w.relation!=='toward');
  const proj  = ev.waypoints.filter(w=>w.relation==='toward')[0] || null;
  // oblast-only event: a zone flare, no track
  if(!pts.length && zones.length) return { zones:zones.map(z=>z.oblast), track:null, isNew:false };
  if(!pts.length) return { zones:[], track:null, isNew:false };

  const last = pts[pts.length-1];
  const np = [last.lon, last.lat];
  const ids = Array.from(this.tracks.keys()).sort();
  let hit = null;
  for(const id of ids){
    const tr = this.tracks.get(id);
    if(tr.targetClass !== ev.targetClass) continue;
    if(tr.status === 'expired') continue;
    const lp = tr.points[tr.points.length-1];
    if(hav([lp.lon,lp.lat], np) > this.cfg.maxKm) continue;
    if((ev.ts - tr.lastSeenTs) > this.cfg.maxDtMin*60000) continue;
    if(tr.headingDeg != null){
      const b = bearing([lp.lon,lp.lat], np);
      if(angDiff(tr.headingDeg, b) > this.cfg.maxTurn) continue;
    }
    hit = tr; break;
  }
  let isNew = false;
  if(!hit){
    const id = ev.targetClass+'-'+(ev.msgId!=null?ev.msgId:(++this._n));
    hit = { id:id, targetClass:ev.targetClass, count:ev.count, points:[],
            projectedTarget:null, headingDeg:ev.heading!=null?ev.heading:null,
            lastSeenTs:ev.ts, status:'active', channels:{}, msgs:[] };
    this.tracks.set(id, hit);
    isNew = true;
  }
  pts.forEach(w=>{
    const p = hit.points[hit.points.length-1];
    if(p && p.name===w.name) return;                 // same place repeated
    hit.points.push({ lat:w.lat, lon:w.lon, ts:ev.ts, msgId:ev.msgId, name:w.name });
  });
  if(hit.points.length>=2){
    const a=hit.points[hit.points.length-2], b=hit.points[hit.points.length-1];
    hit.headingDeg = bearing([a.lon,a.lat],[b.lon,b.lat]);
  } else if(ev.heading!=null) hit.headingDeg = ev.heading;
  if(proj) hit.projectedTarget = { name:proj.name, lat:proj.lat, lon:proj.lon };
  if(ev.count) hit.count = ev.count;
  hit.lastSeenTs = ev.ts;
  hit.status = 'active';
  if(ev.channel) hit.channels[ev.channel] = 1;
  hit.msgs.push({ ts:ev.ts, channel:ev.channel, text:ev.rawText });
  if(hit.msgs.length>40) hit.msgs.shift();
  return { zones:zones.map(z=>z.oblast), track:hit, isNew:isNew };
};
Tracker.prototype.age = function(now){
  now = now||Date.now();
  const gone = [];
  this.tracks.forEach((tr,id)=>{
    const min = (now - tr.lastSeenTs)/60000;
    tr.status = min > this.cfg.expireMin ? 'expired' : (min > this.cfg.staleMin ? 'stale' : 'active');
    tr.fresh  = min <= this.cfg.staleMin;
    if(min > this.cfg.expireMin*4) gone.push(id);
  });
  gone.forEach(id=>this.tracks.delete(id));
  return this.list();
};
Tracker.prototype.list = function(){
  return Array.from(this.tracks.values())
    .filter(t=>t.status!=='expired')
    .sort((a,b)=>b.lastSeenTs-a.lastSeenTs);
};
Tracker.prototype.reset = function(){ this.tracks.clear(); this._n=0; };

/* ---------- name → coords resolution (gazetteer, then cached Nominatim) ---------- */
const CACHE_KEY = 'd9tg.geocache';
function loadCache(){ try{ return JSON.parse(localStorage.getItem(CACHE_KEY)||'{}'); }catch(e){ return {}; } }
function saveCache(c){ try{ localStorage.setItem(CACHE_KEY, JSON.stringify(c)); }catch(e){} }
let CACHE = loadCache();
function resolveName(name){
  const t = norm(name);
  for(const {s,e} of IDX){ if(t.indexOf(s)===0) return { lat:e.ll[1], lon:e.ll[0], src:'gaz' }; }
  const c = CACHE[t];
  return c ? { lat:c[1], lon:c[0], src:'cache' } : null;
}
async function geocode(name){
  const t = norm(name);
  if(CACHE[t]) return { lat:CACHE[t][1], lon:CACHE[t][0], src:'cache' };
  const url = 'https://nominatim.openstreetmap.org/search?format=json&limit=1&countrycodes=ua&q='+encodeURIComponent(name);
  const r = await fetch(url, { headers:{ 'Accept':'application/json' } });
  if(!r.ok) throw new Error('geocode '+r.status);
  const j = await r.json();
  if(!j || !j.length) return null;
  CACHE[t] = [parseFloat(j[0].lon), parseFloat(j[0].lat)];
  saveCache(CACHE);
  return { lat:CACHE[t][1], lon:CACHE[t][0], src:'osm' };
}

/* ---------- air-raid alerts (public JSON, no token) ---------- */
async function fetchAlerts(){
  const r = await fetch('https://ubilling.net.ua/aerialalerts/?json=true', { cache:'no-store' });
  if(!r.ok) throw new Error('alerts '+r.status);
  const j = await r.json();
  const states = j.states || j || {};
  const out = [];
  Object.keys(states).forEach(k=>{
    const v = states[k];
    const on = v === true || (v && (v.alertnow === true || v.enabled === true));
    if(!on) return;
    const nk = norm(k);
    const ob = OBLASTS.find(o=>o.st.some(s=>nk.indexOf(s)===0 || nk.indexOf(s)>=0));
    out.push({ raw:k, oblast:ob?ob.n:null, ll:ob?ob.ll:null });
  });
  return out;
}

